class TestReoptimizedLeader:
    """Leader's scale and allocation chosen at the entry demand."""

    @pytest.mark.parametrize("scale", SCALES)
    def test_trigger_and_policy_at_baseline(self, games, scale):
        game = games[scale]
        X_P, K_L, phi_L = REOPTIMIZED[0.10, 1.5, scale]
        below, *_ = game.reoptimized_gap(0.98 * X_P, (K_L, phi_L))
        above, *_ = game.reoptimized_gap(1.02 * X_P, (K_L, phi_L))
        assert below < 0.0 < above
        K, phi, lead = game.leader_best_policy(X_P, (K_L, phi_L))
        assert pytest.approx(K_L, rel=2e-3) == K
        assert phi == pytest.approx(phi_L, abs=5e-4)
        assert phi < game.phi_star - 0.005
        follow = float(game.subgame(K, phi).follower_value(X_P)[0])
        assert lead == pytest.approx(follow, rel=2e-4)

    def test_cold_start_finds_the_same_policy(self, games):
        game = games["envelope"]
        X_P, K_L, phi_L = REOPTIMIZED[0.10, 1.5, "envelope"]
        K, phi, _ = game.leader_best_policy(X_P)
        assert pytest.approx(K_L, rel=2e-3) == K
        assert phi == pytest.approx(phi_L, abs=5e-4)

    @pytest.mark.parametrize("scale", SCALES)
    def test_finite_differences_agree_at_the_equilibrium_policy(self, games, scale):
        game = games[scale]
        X_P, K_L, phi_L = REOPTIMIZED[0.10, 1.5, scale]
        fd = game.finite_difference_subgame(K_L, phi_L, n_grid=6001)
        fixed = game.rent_equalization(K_L, phi_L)
        assert fd["X_P"] == pytest.approx(fixed["X_P"], rel=2e-4)
        gap_at_trigger = np.interp(np.log(X_P), np.log(fd["X"]), fd["gap"])
        follower = np.interp(np.log(X_P), np.log(fd["X"]), fd["follower"])
        assert abs(gap_at_trigger) / follower < 2e-3

    def test_trigger_relative_to_other_triggers(self, games, single, reduced):
        """Above the single-firm post-switch trigger and the reduced-model X_P,
        below the follower's post-switch entry trigger."""
        X_P, K_L, phi_L = REOPTIMIZED[0.10, 1.5, "envelope"]
        sub = games["envelope"].subgame(K_L, phi_L)
        assert single.X_H < X_P < sub.post_switch.X_F
        assert X_P > 3.0 * 0.0027
        assert reduced["K_star"] * 2.0 < K_L


