def _ode_residual(claim, forcing, params, X, h=1e-3):
    """Relative residual of the L-regime ODE at X, by differences in log X."""
    p = params
    v_lo, v, v_hi = (float(claim(X * np.exp(s * h))[0]) for s in (-1.0, 0.0, 1.0))
    d1 = (v_hi - v_lo) / (2.0 * h)
    d2 = (v_hi - 2.0 * v + v_lo) / h**2
    s2 = 0.5 * p.sigma**2
    resid = s2 * (d2 - d1) + p.mu_L * d1 - (p.r + p.lam) * v + forcing(X)
    return resid / ((p.r + p.lam) * v)


class TestPrimitives:
    def test_contest_revenue_limits(self):
        assert contest_revenue(2.0, 0.0, 0.4) == pytest.approx(2.0**0.4)
        assert contest_revenue(0.0, 1.0, 0.4) == 0.0
        assert contest_revenue(1.0, 1.0, 0.4) == pytest.approx(0.5)

    def test_revenue_coeff_matches_duopoly_module(self, params, games):
        duo = DuopolyModel(params)
        game = games["envelope"]
        for phi, K, phi_j, K_j in [(0.7, 0.01, 0.5, 0.2), (0.3, 0.5, 0.9, 0.004)]:
            expected = duo._effective_revenue_coeff(phi, K, phi_j, K_j)
            assert float(game.revenue_coeff(phi, K, phi_j, K_j)) == pytest.approx(
                expected, rel=1e-12
            )
        mono = duo._effective_revenue_coeff(0.7, 0.01, 0.0, 0.0, monopolist=True)
        assert float(game.revenue_coeff(0.7, 0.01, 0.0, 0.0)) == pytest.approx(
            mono, rel=1e-12
        )

    def test_rejects_bad_inputs(self, params):
        with pytest.raises(ValueError, match="scale"):
            ExactPreemptionGame(params, "fixed")
        with pytest.raises(ValueError, match="alpha"):
            ExactPreemptionGame(params.with_param(alpha=0.5, sigma=0.36))


class TestForcedClaim:
    def test_closed_form_solves_the_ode(self, params):
        low = ((2.0, params.beta_H), (0.3, 1.0))
        high = ((1.5, 1.0), (-0.002, 0.0))
        claim = ForcedClaim(params, 0.01, low, high)

        def forcing(X):
            terms = low if X < 0.01 else high
            return sum(c * X**q for c, q in terms)

        for X in (1e-4, 0.003, 0.009, 0.02, 0.5):
            assert abs(_ode_residual(claim, forcing, params, X)) < 1e-6

    def test_value_and_slope_continuous_at_breakpoint(self, params):
        claim = ForcedClaim(params, 0.01, ((2.0, params.beta_H),), ((1.5, 1.0),))
        eps = 1e-7
        below = float(claim(0.01 * (1.0 - eps))[0])
        above = float(claim(0.01 * (1.0 + eps))[0])
        assert below == pytest.approx(above, rel=1e-5)
        slope_lo = (below - float(claim(0.01 * (1.0 - 2e-4))[0])) / 2e-4
        slope_hi = (float(claim(0.01 * (1.0 + 2e-4))[0]) - above) / 2e-4
        assert slope_lo == pytest.approx(slope_hi, rel=5e-3)

    def test_table_reproduces_closed_form(self, params):
        low = ((2.0, params.beta_H),)
        high = ((1.5, 1.0), (-0.002, 0.0))
        exact = ForcedClaim(params, 0.01, low, high)
        y = np.geomspace(0.01, 1e7, 1351)
        table = ForcedClaim(params, 0.01, low, table=(y, 1.5 * y - 0.002))
        X = np.array([1e-4, 0.005, 0.02, 0.3, 40.0, 1e4, 5e6])
        np.testing.assert_allclose(table(X), exact(X), rtol=2e-6)

    def test_table_keeps_precision_far_above_the_breakpoint(self):
        """A large positive root makes the upper integral decay fast; it must
        not be obtained by differencing a cumulative integral."""
        params = ModelParameters(lam=0.5)
        low = ((2.0, params.beta_H),)
        exact = ForcedClaim(params, 0.01, low, ((1.5, 1.0),))
        y = np.geomspace(0.01, 1e7, 1351)
        table = ForcedClaim(params, 0.01, low, table=(y, 1.5 * y))
        X = np.array([1.0, 60.0, 1e3, 1e5])
        np.testing.assert_allclose(table(X), exact(X), rtol=2e-6)

    def test_table_rejects_demand_above_range(self, params):
        y = np.geomspace(0.01, 1.0, 201)
        table = ForcedClaim(params, 0.01, ((2.0, 1.5),), table=(y, y))
        with pytest.raises(ValueError, match="tabulated range"):
            table(2.0)


class TestFiniteDifferenceSolver:
    def test_linear_ode_power_forcing(self, params):
        """Without an obstacle a power forcing has solution f / (-Q(p))."""
        p = params
        X = np.geomspace(1e-6, 1e3, 4001)
        V, active = solve_forced_ode(X, X**1.3, p.sigma, p.mu_L, p.r + p.lam)
        Q = 0.5 * p.sigma**2 * 1.3 * 0.3 + p.mu_L * 1.3 - (p.r + p.lam)
        np.testing.assert_allclose(V, X**1.3 / -Q, rtol=1e-4)
        assert not active.any()

    def test_obstacle_recovers_single_firm_h_regime_option(self, params, single):
        """LCP in the absorbing regime: B_H X^{beta_H} below the trigger X_H*."""
        p = params
        game = ExactPreemptionGame(params, "envelope")
        X = np.geomspace(1e-5 * single.X_H, 1e4 * single.X_H, 6001)
        payoff = single.envelope_payoff(X)
        V, active = solve_forced_ode(
            X, np.zeros_like(X), p.sigma, p.mu_H, p.r, obstacle=payoff
        )
        boundary = X[np.argmax(active)]
        assert boundary == pytest.approx(single.X_H, rel=1e-2)
        assert active[np.argmax(active) : -1].all()
        below = X < 0.9 * single.X_H
        np.testing.assert_allclose(
            V[below], single.B_H * X[below] ** p.beta_H, rtol=2e-4
        )
        assert pytest.approx(single.X_H, rel=1e-5) == game.post_switch_entry(0.0).X_F


