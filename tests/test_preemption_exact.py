class TestPostSwitchProblem:
    def test_envelope_capacity_tangent_at_trigger(self, games, reduced):
        game = games["envelope"]
        entry = game.post_switch_entry(reduced["phi_star"] * reduced["K_star"])
        K = game.post_switch_capacity(np.array([entry.X_F]), entry.T_L)[0]
        assert pytest.approx(entry.K_F, rel=1e-7) == K
        assert pytest.approx(0.05778, rel=1e-3) == entry.X_F
        assert pytest.approx(0.21320, rel=1e-3) == entry.K_F

    def test_follower_exercises_on_an_upper_set(self, params, games, reduced):
        """H-regime LCP against the installed leader: simplification 1."""
        p = params
        game = games["envelope"]
        T_L = reduced["phi_star"] * reduced["K_star"]
        entry = game.post_switch_entry(T_L)
        X = np.geomspace(1e-5 * entry.X_F, 1e4 * entry.X_F, 6001)
        K = game.post_switch_capacity(X, T_L)
        payoff = p.A_H * contest_revenue(K, T_L, p.alpha) * X - game.cost(K)
        V, active = solve_forced_ode(
            X, np.zeros_like(X), p.sigma, p.mu_H, p.r, obstacle=payoff
        )
        first = int(np.argmax(active))
        assert X[first] == pytest.approx(entry.X_F, rel=1e-2)
        assert active[first:-1].all()
        np.testing.assert_allclose(V, game.post_switch_value(X, entry), rtol=5e-4)

    def test_leader_post_switch_revenue_continuous(self, games, reduced):
        game = games["envelope"]
        K, phi = reduced["K_star"], reduced["phi_star"]
        entry = game.post_switch_entry(phi * K)
        X = entry.X_F * np.array([1.0 - 1e-9, 1.0 + 1e-9])
        lo, hi = game.leader_post_switch_revenue(X, K, phi, entry)
        assert lo == pytest.approx(hi, rel=1e-6)


class TestLeaderClaim:
    def test_inference_only_leader_earns_the_killed_perpetuity(self, params, games):
        """With phi_L = 0 the leader has no stake after the switch, so its claim
        is the inference perpetuity discounted at r + lambda - mu_L, and the
        follower faces no rival in H."""
        p = params
        for game in games.values():
            sub = game.subgame(0.01, 0.0)
            assert pytest.approx(game.X_ref, rel=1e-5) == sub.post_switch.X_F
            X = np.array([1e-3, 0.5 * game.X_ref, 3.0 * game.X_ref, 0.2])
            expected = 0.01**p.alpha * X / (p.r + p.lam - p.mu_L)
            np.testing.assert_allclose(sub.leader_claim(X), expected, rtol=1e-6)

    @pytest.mark.parametrize("scale", SCALES)
    def test_leader_claim_below_monopoly_value(self, games, reduced, scale):
        """Follower entry only dilutes: the claim lies below the monopoly
        installed value A_eff X and converges to it at low demand."""
        game = games[scale]
        K, phi = reduced["K_star"], reduced["phi_star"]
        sub = game.subgame(K, phi)
        X = np.geomspace(1e-7 * sub.post_switch.X_F, 0.9 * sub.post_switch.X_F, 40)
        monopoly = float(game.revenue_coeff(phi, K, 0.0, 0.0)) * X
        claim = sub.leader_claim(X) + sub.leader_premium * X**game.bp
        assert (claim < monopoly).all()
        assert claim[0] / monopoly[0] == pytest.approx(1.0, abs=1e-3)
        assert np.all(np.diff(claim / monopoly) < 0.0)


