@pytest.mark.parametrize("key", list(GRID), ids=lambda k: f"lam{k[0]}-gam{k[1]}-{k[2]}")
class TestGrid:
    """Yes/no answers and triggers on the grid of issue #173."""

    def test_single_firm_benchmark(self, key, grid_game):
        entry = grid_game(key).single_firm()
        expected = GRID[key]["single_X"]
        assert entry.enters == (expected is not None)
        if expected is not None:
            assert entry.X_entry == pytest.approx(expected, rel=2e-3)

    def test_leader_at_paper_policy(self, key, grid_game):
        game = grid_game(key)
        result = game.rent_equalization(*game.paper_policy())
        expected = GRID[key]["paper_X_P"]
        assert bool(result["exists"]) == (expected is not None)
        assert result["max_gap_over_follower"] == pytest.approx(
            GRID[key]["paper_gap"], abs=1e-3
        )
        if expected is not None:
            assert result["X_P"] == pytest.approx(expected, rel=1e-3)

    def test_leader_at_exact_monopoly_scale(self, key, grid_game):
        game = grid_game(key)
        result = game.rent_equalization(*game.exact_monopoly_policy())
        assert result["exists"] == 1.0
        assert result["X_P"] == pytest.approx(GRID[key]["mono_X_P"], rel=1e-3)

    def test_reoptimized_leader(self, key, grid_game):
        """The pinned policy equalizes rents at X_P and is a local maximum of
        the leader's own entry NPV there (the full fixed-point search runs at
        baseline in TestReoptimizedLeader)."""
        game = grid_game(key)
        X_P, K_L, phi_L = GRID[key]["reopt"]
        sub = game.subgame(K_L, phi_L)
        lead = float(sub.leader_value(X_P)[0])
        follow = float(sub.follower_value(X_P)[0])
        assert lead == pytest.approx(follow, rel=2e-4)
        for dK, dphi in ((1.03, 0.0), (0.97, 0.0), (1.0, 0.01), (1.0, -0.01)):
            other = game.subgame(K_L * dK, phi_L + dphi).leader_value(X_P)[0]
            assert other < lead
        assert phi_L < game.phi_star
        wait = float(game.mutual_waiting_claim("reoptimized")(X_P)[0])
        assert lead / wait == pytest.approx(GRID[key]["lead_over_wait"], abs=5e-3)
        assert lead > wait
